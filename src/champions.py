"""Part 2: did Leicester win differently from the other 2015/16 champions?

Compares Leicester, Barcelona, Juventus and PSG, each against its own league
average. Bayern is left out: the free data only covers Leverkusen's Bundesliga
matches. Run after train.py.
"""

import matplotlib.pyplot as plt
from matplotlib.ticker import PercentFormatter

from analysis import FIGURES_DIR, GRAY, INK, LEICESTER_BLUE, LIGHT_GRAY, MUTED, style
from team_stats import LEICESTER, champion_summary, load, ordinal

SHORT_NAMES = {"Leicester City": "Leicester", "Barcelona": "Barcelona", "Juventus": "Juventus",
               "Paris Saint-Germain": "PSG"}
PANELS = [
    ("shots_vs_league", "Shots per match", "pct"),
    ("quality_vs_league", "xG per shot", "pct"),
    ("finishing", "Goals minus xG", "goals"),
    ("shots_against_vs_league", "Shots conceded per match", "pct"),
    ("quality_against_vs_league", "xG per shot conceded", "pct"),
    ("goals_prevented", "xG against minus goals conceded", "goals"),
]


def plot_champions(summary) -> None:
    fig, axes = plt.subplots(2, 3, figsize=(12, 6.5))
    names = [SHORT_NAMES[t] for t in summary.index][::-1]
    colors = [LEICESTER_BLUE if t == LEICESTER else LIGHT_GRAY for t in summary.index][::-1]
    for ax, (col, label, kind) in zip(axes.flat, PANELS, strict=True):
        values = summary[col].values[::-1]
        ax.barh(names, values, color=colors, height=0.7)
        ax.axvline(0, color=MUTED, linewidth=1)
        style(ax)
        ax.tick_params(axis="y", length=0)
        if kind == "pct":
            ax.xaxis.set_major_formatter(PercentFormatter(1.0, decimals=0))
            ax.set_title(f"{label}\nvs league average", loc="left", fontsize=10, color=INK)
        else:
            ax.set_title(f"{label}\n(goals over the season)", loc="left", fontsize=10, color=INK)
        for y, v in enumerate(values):
            text = f"{v:+.0%}" if kind == "pct" else f"{v:+.1f}"
            ax.text(v, y, f" {text} " if v >= 0 else f" {text} ", va="center",
                    ha="left" if v >= 0 else "right", fontsize=8.5, color=GRAY)
        lo, hi = min(values.min(), 0), max(values.max(), 0)
        pad = (hi - lo) * 0.3
        ax.set_xlim(lo - (pad if lo < 0 else 0), hi + (pad if hi > 0 else 0))
    lei = summary.loc[LEICESTER]
    others = summary.drop(LEICESTER)
    fig.suptitle(f"The other champions out-shot their leagues by {others.shots_vs_league.min():.0%} to "
                 f"{others.shots_vs_league.max():.0%} and beat their xG.\n"
                 f"Leicester took a near-average number of shots ({lei.shots_vs_league:+.0%}) "
                 "and won on chance quality and defense",
                 x=0.03, y=0.99, ha="left", fontsize=11.5, color=INK)
    fig.text(0.03, -0.01, "Non-penalty shots, 2015/16. Each team compared with the average team in its own league. "
             "Bayern not shown: the free data covers only Leverkusen's Bundesliga matches. PSG: 37 of 38 matches.",
             fontsize=8, color=MUTED)
    fig.tight_layout(rect=(0, 0, 1, 0.95))
    fig.savefig(FIGURES_DIR / "champions.png", dpi=150, bbox_inches="tight")
    plt.close(fig)


def main() -> None:
    shots, matches = load()
    summary = champion_summary(shots, matches)
    plot_champions(summary)

    lei, others = summary.loc[LEICESTER], summary.drop(LEICESTER)
    lines = [
        "# Part 2 results: Leicester vs the other champions",
        "",
        "Generated by `src/champions.py`. Non-penalty shots; each team vs its own league's average team.",
        "Bayern is excluded (the free Bundesliga data covers only Leverkusen). PSG has 37 of 38 matches.",
        "",
        "## Key numbers",
        "",
        *[f"- {SHORT_NAMES[t]}: {r.shots_vs_league:+.0%} shots, {r.quality_vs_league:+.0%} xG per shot, "
          f"{r.finishing:+.1f} goals vs xG, {r.goals_prevented:+.1f} goals prevented, "
          f"{r.points:.0f} points from {r.xpts:.1f} expected ({ordinal(r.xpts_rank)} on expected points), "
          f"counter xG {r.counter_xg_ratio:.1f}x league share"
          for t, r in summary.iterrows()],
        "",
        f"Leicester's xG difference per match was {lei.xg_diff_per_match:+.2f}, against "
        f"{others.xg_diff_per_match.min():+.2f} to {others.xg_diff_per_match.max():+.2f} "
        "for the other champions.",
        "",
        "## Full table",
        "",
        summary.round(3).to_markdown(),
        "",
    ]
    (FIGURES_DIR / "champions_results.md").write_text("\n".join(lines))
    print("\n".join(lines[:14]))


if __name__ == "__main__":
    main()
